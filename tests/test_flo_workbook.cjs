'use strict';
const assert = require('node:assert/strict');
const WB = require('../web/flo-workbook.js');
const Flo = require('../web/mascot.js');
let n=0;
const ok=(x,label)=>{assert.ok(x,label);n++;};
const eq=(x,y,label)=>{assert.equal(x,y,label);n++;};
const close=(x,y,label)=>{assert.ok(Math.abs(x-y)<1e-7*Math.max(1,Math.abs(y)),label+': '+x+' vs '+y);n++;};
ok(WB.match('open Excel modeling lab'),'detect Excel Lab');
ok(WB.match('模拟 Excel 表格练习'),'Chinese workbook route');
ok(!WB.match('teach NVDA DCF step by step'),'DCF Academy still handles tutor');
const bookIds=['dcf','three','comps','ddm','dupont','reserves'];
for(const id of bookIds){
  const s=WB.newSession(id);
  ok(s.cells&&s.answers&&s.template.id===id,id+' template exists');
  const targets=Object.keys(s.answers);
  ok(targets.length>=2,id+' has graded formula challenge cells');
  const grade0=WB.score(s);
  ok(grade0.correct<grade0.total,id+' starts in practice mode');
  targets.forEach(ref=>WB.setCell(s,ref,s.answers[ref]));
  const grade=WB.score(s);
  eq(grade.correct,grade.total,id+' instructor formulas match reference');
  ok(Number.isFinite(WB.evaluate(s.cells,s.template.final)),id+' final output numeric');
  const scenario=s.template.scenario.at(-1);
  WB.useScenario(s,s.template.scenario.length-1);
  eq(s.scenario,s.template.scenario.length-1,id+' scenario applied');
  ok(Number.isFinite(WB.evaluate(s.cells,s.template.final)),id+' scenario recalculates');
  const first=targets[0];
  WB.setCell(s,first,'=1+2');
  ok(WB.score(s).correct<targets.length,id+' incorrect formula graded');
  WB.setCell(s,first,s.answers[first]);
}
const d=WB.newSession('dcf');
for(const [ref,v] of Object.entries(d.answers))WB.setCell(d,ref,v);
close(WB.evaluate(d.cells,'C3'),1120,'DCF year 1 revenue 1000*(1+.12)');
close(WB.evaluate(d.cells,'C6'),336,'DCF EBIT 1120*.30');
close(WB.evaluate(d.cells,'C15'),327.2-134.4-9.6,'DCF FCFF 265?');
close(WB.evaluate(d.cells,'G26'),WB.evaluate(d.cells,'G24')/100,'DCF per share equity / diluted shares');
WB.setCell(d,'B16',.02);
assert.throws(()=>WB.evaluate(d.cells,'G20'),/#WACC|#DIV/);n++;
const d0=WB.newSession('three');
for(const [ref,f] of Object.entries(d0.answers))WB.setCell(d0,ref,f);
for(const ref of ['B30','C30','D30','E30'])close(WB.evaluate(d0.cells,ref),0,'three-statement assets = liabilities + equity '+ref);
const c=WB.newSession('comps');
for(const [ref,f] of Object.entries(c.answers))WB.setCell(c,ref,f);
close(WB.evaluate(c.cells,'D6'),10,'median multiple 10x');
close(WB.evaluate(c.cells,'E12'),18.5,'target price');
const y=WB.newSession('ddm');for(const [ref,f] of Object.entries(y.answers))WB.setCell(y,ref,f);
ok(WB.evaluate(y.cells,'G10')>0,'positive DDM price');
const dup=WB.newSession('dupont');
for(const [ref,f] of Object.entries(dup.answers))WB.setCell(dup,ref,f);
close(WB.evaluate(dup.cells,'D10'),.30,'FY2 DuPont ROE 30%');
close(WB.evaluate(dup.cells,'D12'),0,'DuPont reconciliation');
const res=WB.newSession('reserves');
for(const [ref,f] of Object.entries(res.answers))WB.setCell(res,ref,f);
close(WB.evaluate(res.cells,'G3'),40,'reserve closing');
close(WB.evaluate(res.cells,'G5'),0,'reserve disclosure reconciliation');
close(WB.evaluate(res.cells,'G6'),.4,'reserve releases 40% opening');
WB.setCell(res,'G3','=G3+1');
assert.throws(()=>WB.evaluate(res.cells,'G3'),/#CYCLE!/);n++;
WB.setCell(res,'G3','=B3/0');
assert.throws(()=>WB.evaluate(res.cells,'G3'),/#DIV\/0!/);n++;
WB.setCell(res,'G3','=EVIL(B3)');
assert.throws(()=>WB.evaluate(res.cells,'G3'),/#NAME\?/);n++;
assert.throws(()=>WB.setCell(res,'B3','document.cookie'),/Enter a number/);n++;
assert.throws(()=>WB.setCell(res,'B3','<script>alert(1)</script>'),/Enter a number/);n++;
const csv=WB.safeCSV(d);
ok(csv.includes('HYPOTHETICAL DATA ONLY')&&!csv.includes('=SUM(C18:G18)'), 'CSV does not export executable formulas');
(async()=>{
  const ix={companies:[{cik:1045810,ticker:'NVDA',name:'NVIDIA'}]};
  const ret=await Flo.ask('open Excel modeling lab',ix);
  ok(ret.workbook===true&&ret.html.includes('data-ffwb="dcf"'),'Flo chat embeds workbook');
  const ret2=await Flo.ask('open three-statement spreadsheet practice',ix);
  ok(ret2.workbook===true&&ret2.html.includes('data-ffwb="three"'),'Flo chooses specific spreadsheet');
  console.log(n+' Flo modeling workbook checks passed');
})().catch(e=>{console.error(e);process.exitCode=1;});
