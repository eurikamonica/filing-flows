"""Earnings releases the reader used to reject (Meta, CACI, Southwest, Las Vegas Sands, Sonoco) and exhibit names it missed."""
import datetime as dt
import re

from pipeline import build, release

ROW = '<tr><td>{}</td><td>$</td><td>{}</td><td>$</td><td>{}</td>{}</tr>'


def _table(rows, title="", pct=False):
    extra = '<td>8.2</td><td>%</td>' if pct else ''
    body = ''.join(ROW.format(l, a, b, extra) for l, a, b in rows)
    head = '<tr><td></td><td colspan="4">Three Months Ended September 30,</td></tr><tr><td></td><td>2026</td><td>2025</td></tr>'
    return f'<table>{"<tr><td>" + title + "</td></tr>" if title else ""}{head}{body}</table>'


IS = [("Revenue", "64,601", "51,242"), ("Cost of revenue", "13,369", "9,206"), ("Income from operations", "12,988", "20,535"),
      ("Income before provision for income taxes", "13,001", "21,138"), ("Provision for income taxes", "3,141", "18,954"),
      ("Net income", "9,860", "2,184")]


def _doc(*parts):
    return "<html><body><p>Results for the quarter ended September 30, 2026</p>" + "".join(parts) + "</body></html>"


def test_footnote_about_non_gaap_above_the_statement():
    # Meta: the previous page ends with a footnote on non-GAAP measures, right above the statement's own title
    html = _doc("<p>(In millions)</p><p>For a reconciliation of GAAP to non-GAAP measures, see the table below.</p>",
                _table(IS, "CONDENSED CONSOLIDATED STATEMENTS OF INCOME"))
    r = release.parse(html, dt.date(2026, 10, 21))
    assert r["end"] == "2026-09-30" and r["is"]["revenue"] == 64601e6 and r["is"]["pl"] == 9860e6


def test_title_above_the_table_nearer_than_the_non_gaap_note():
    # Las Vegas Sands, Lithia: the title is printed above the table, a non-GAAP paragraph further up
    html = _doc("<p>Adjusted EBITDA is a non-GAAP measure.</p><p>Condensed Consolidated Statements of Operations</p>"
                "<p>(In millions)</p>", _table(IS))
    assert release.parse(html, dt.date(2026, 10, 21))["is"]["revenue"] == 64601e6


def test_percent_change_column_and_operating_revenues():
    rows = [("Total operating revenues", "8,422", "7,224")] + IS[2:]
    html = _doc("<p>(In millions)</p>", _table(rows, "Consolidated Statement of Income", pct=True))
    r = release.parse(html, dt.date(2026, 10, 21))
    assert r["is"]["revenue"] == 8422e6 and r["is"]["pl"] == 9860e6


def test_slash_labels():
    assert release.PATTERNS["pl"].search(release.norm_label("Net (loss)/income"))
    assert release.PATTERNS["oi"].search(release.norm_label("Operating (loss)/profit"))


def test_exhibit_names():
    pats = build.EXHIBIT_PATTERNS
    for name in ("meta-09302026xexhibit991.htm", "wdfc-20261021xexx991.htm", "osbc-ex99d1.htm", "ex-99_1.htm", "exhibit991102126.htm"):
        assert any(re.search(p, name, re.I) for p in pats), name
    assert build.NOT_EXHIBIT.search("R1.htm") and not build.NOT_EXHIBIT.search("spaceexplorationtechnologi.htm")


def test_ifrs_income_statement_wording():
    """IFRS releases (Ferrari): "Operating profit (EBIT)", "Profit before taxes", "Income tax expenses", "Net profit",
    "(Euro million)"; a full statement under a non-GAAP section title still beats a highlights table."""
    from pipeline import release as R
    for key, lab in [("oi", "operating profit (ebit)"), ("pretax", "profit before taxes"), ("tax", "income tax expenses"),
                     ("pl", "net profit"), ("pl", "profit for the period"), ("ni", "net profit attributable to owners of the parent"),
                     ("nci", "net profit attributable to non-controlling interests"), ("sga", "selling, general and administrative costs"),
                     ("rd", "research and development costs")]:
        assert R.PATTERNS[key].search(lab), (key, lab)
    assert not R.PATTERNS["pl"].search("gross profit")
    assert R._units({"before": "", "text": "For the three months ended (Euro million) June 30"}) == 1e6
    assert R._units({"before": "", "text": "(€ million, except per share data)"}) == 1e6
    assert R._units({"before": "", "text": "(in euro thousands)"}) == 1e3


def test_foreign_release_conventions():
    """6-K results of other foreign filers: "DKK million" captions (Novo Nordisk), "Profit (loss) after tax" and
    "Attributable to owners of parent" (SAP), "NET REVENUE (Notes 20, 31 and 37)" (TSMC), European dates and a bare
    "Q2 2026" header for the quarter end."""
    import datetime as dt
    from pipeline import release as R
    assert R._units({"before": "", "text": "DKK million Q2 2026 Q2 2025 Net sales 78,488"}) == 1e6
    assert R.PATTERNS["pl"].search("profit (loss) after tax") and R.PATTERNS["pl"].search("profit after income taxes")
    assert R.PATTERNS["ni"].search("attributable to owners of parent") and R.PATTERNS["nci"].search("attributable to non-controlling interests")
    assert R.PATTERNS["revenue"].search(R.norm_label("NET REVENUE (Notes 20, 31 and 37)"))
    assert R.PATTERNS["ocf"].search("net cash generated by operating activities")
    t = {"rows": [], "text": "DKK million Q2 2026 Q2 2025", "before": "", "header": "Q2 2026 Q2 2025"}
    assert R.period_end("for the period 1 January to 30 June 2026", t, dt.date(2026, 8, 4)) == dt.date(2026, 6, 30)
    assert R.period_end("Financial highlights Q2 2026", t, dt.date(2026, 8, 4)) == dt.date(2026, 6, 30)
    assert R.period_end("Financial highlights Q2 2026", t, dt.date(2025, 11, 4)) is None   # a fiscal Q2 that is not June


def test_revenue_heading_without_total_is_summed():
    """Wix prints "Revenues" as a heading over its two lines, with no total: the lines are summed."""
    from pipeline import release as R
    rows = [{"key": "revenues", "label": "Revenues", "vals": [], "pct": False, "cells": []},
            {"key": "creative subscriptions", "label": "x", "vals": [398.0, 345.0], "pct": False, "cells": []},
            {"key": "business solutions", "label": "x", "vals": [165.0, 144.0], "pct": False, "cells": []},
            {"key": "cost of revenues", "label": "x", "vals": [], "pct": False, "cells": []},
            {"key": "gross profit", "label": "x", "vals": [370.0, 336.0], "pct": False, "cells": []},
            {"key": "net income (loss)", "label": "x", "vals": [-76.0, 58.0], "pct": False, "cells": []}]
    m = R._map_rows({"rows": rows}, R.IS_KEYS, full=True)
    assert m["revenue"][2] == [563.0, 489.0] and m["gp"][0] == 370.0 and m["pl"][0] == -76.0


def test_inline_xbrl_quarter_with_resources_elsewhere():
    """A 6-K report with no tables (positioned text, TD Bank) is read from its inline XBRL tags; its contexts and
    units can sit in another document of the filing; the shortest period is the quarter; the year-ago period too."""
    import datetime as dt
    from pipeline import ixbrl
    res = """<ix:resources>
    <xbrli:context id="Q"><xbrli:entity/><xbrli:period><xbrli:startDate>2026-05-01</xbrli:startDate><xbrli:endDate>2026-07-31</xbrli:endDate></xbrli:period></xbrli:context>
    <xbrli:context id="YTD"><xbrli:entity/><xbrli:period><xbrli:startDate>2025-11-01</xbrli:startDate><xbrli:endDate>2026-07-31</xbrli:endDate></xbrli:period></xbrli:context>
    <xbrli:context id="PY"><xbrli:entity/><xbrli:period><xbrli:startDate>2025-05-01</xbrli:startDate><xbrli:endDate>2025-07-31</xbrli:endDate></xbrli:period></xbrli:context>
    <xbrli:context id="SEG"><xbrli:entity><xbrli:segment><xbrldi:explicitMember dimension="a">b</xbrldi:explicitMember></xbrli:segment></xbrli:entity><xbrli:period><xbrli:startDate>2026-05-01</xbrli:startDate><xbrli:endDate>2026-07-31</xbrli:endDate></xbrli:period></xbrli:context>
    <xbrli:unit id="CAD"><xbrli:measure>iso4217:CAD</xbrli:measure></xbrli:unit></ix:resources>"""
    doc = """<div>Third quarter <ix:nonFraction name="ifrs-full:Revenue" contextRef="Q" unitRef="CAD" scale="6">16,885</ix:nonFraction>
    <ix:nonFraction name="ifrs-full:Revenue" contextRef="YTD" unitRef="CAD" scale="6">48,000</ix:nonFraction>
    <ix:nonFraction name="ifrs-full:Revenue" contextRef="SEG" unitRef="CAD" scale="6">9,000</ix:nonFraction>
    <ix:nonFraction name="ifrs-full:ProfitLoss" contextRef="Q" unitRef="CAD" scale="6">4,615</ix:nonFraction>
    <ix:nonFraction name="ifrs-full:IncomeTaxExpenseContinuingOperations" contextRef="Q" unitRef="CAD" scale="6" sign="-">12</ix:nonFraction>
    <ix:nonFraction name="ifrs-full:Revenue" contextRef="PY" unitRef="CAD" scale="6">15,297</ix:nonFraction>
    <ix:nonFraction name="ifrs-full:ProfitLoss" contextRef="PY" unitRef="CAD" scale="6">3,000</ix:nonFraction></div>"""
    r = ixbrl.release(doc, dt.date(2026, 8, 27), res)
    assert r["end"] == "2026-07-31" and r["span"] == 91 and r["is_quarter"] and r["currency"] == "CAD"
    assert r["is"]["revenue"] == 16885e6 and r["is"]["pl"] == 4615e6 and r["is"]["tax"] == -12e6
    assert r["py_end"] == "2025-07-31" and r["py"]["revenue"] == 15297e6
