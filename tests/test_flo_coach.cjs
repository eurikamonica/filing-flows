'use strict';
const assert=require('node:assert/strict');
const Coach=require('../web/flo-coach.js');
const WB=require('../web/flo-workbook.js');
const Real=require('../web/flo-real-workbook.js');
const SEC=require('../web/flo-real-data.js');
let n=0;
const ok=(v,msg)=>{assert.ok(v,msg);n++};
const eq=(x,y,msg)=>{assert.equal(x,y,msg);n++};
const close=(x,y,msg)=>{assert.ok(Math.abs(x-y)<1e-7*Math.max(1,Math.abs(y)),msg+': got '+x+' expected '+y);n++};
for(const id of ['dcf','three','comps','ddm','dupont','reserves']){
 const s=WB.newSession(id),tracks=Coach.track(s);
 ok(tracks.length>=2&&tracks.every(x=>x.length===5),id+' bilingual guided track');
 ok(Coach.panel(s,'zh').includes('Flo Guided Coach')&&Coach.panel(s,'zh').includes('Concept checkpoint')===false,
    id+' lesson renders Chinese and quiz');
 eq(Coach.next(s),false,id+' cannot skip blank formula');
 eq(s.selected,tracks[0][0],id+' blank formula focused');
 eq(Coach.state(s).step,0,id+' remains at step zero');
 for(const [cell,formula] of Object.entries(s.answers))WB.setCell(s,cell,formula);
 eq(Coach.completed(s,tracks[0][0]),true,id+' correct checked formula');
 ok(Coach.next(s),id+' advance after formula correct');
 eq(Coach.state(s).step,1,id+' coach state advance');
 eq(Coach.prev(s),0,id+' coach step back');
 ok(Coach.hint(s,'zh').length>10,id+' detailed Chinese formula reasoning');
 const q=Coach.questions[id][0];
 eq(Coach.answerQuiz(s,q.correct,'zh'),true,id+' concept question correct');
 eq(Coach.state(s).quizzesAnswered,1,id+' quiz achievement');
}
for(const id of ['NVDA','AAPL','MSFT','SUNBEAM','DELL','WORLDCOM','XEROX','WASTE']){
 const s=Real.make(id),steps=Coach.track(s);
 ok(steps.length>=2,id+' SEC guided steps');
 for(const [ref,formula] of Object.entries(s.answers))Real.set(s,ref,formula);
 eq(Real.check(s).correct,Object.keys(s.answers).length,id+' SEC case all formulas correct');
 ok(Coach.panel(s,'en').includes('Concept checkpoint'),id+' SEC quiz visible');
 ok(Coach.current(s)[0] in s.answers,id+' guidance targets present');
 ok(Coach.next(s),id+' guided next after right formula');
 const q=Coach.questions[id][0];
 eq(Coach.answerQuiz(s,q.correct,'en'),true,id+' SEC quiz score');
}
const world=Real.make('WORLDCOM');
for(const [r,x] of Object.entries(world.answers))Real.set(world,r,x);
eq(Real.get(world,'C3'),3852,'WorldCom SEC alleged 2001 + 2002Q1 $3,852M');
close(Real.get(world,'C4'),3055/3852,'WorldCom FY2001 share of combined alleged amount');
ok(world.source.startsWith('https://www.sec.gov/'),'WorldCom SEC source');
const xerox=Real.make('XEROX');
for(const [r,x] of Object.entries(xerox.answers))Real.set(xerox,r,x);
eq(Real.get(xerox,'C3'),3000,'Xerox revenue lower bound, NOT actual precise amount');
eq(Real.get(xerox,'C4'),1500,'Xerox approximate pretax impact, NOT ratio');
ok(/MORE THAN/i.test(xerox.cells.B3.note),'Xerox lower bound labeled clearly');
const waste=Real.make('WASTE');
for(const [r,x] of Object.entries(waste.answers))Real.set(waste,r,x);
eq(Real.get(waste,'B3'),1700,'Waste Management multiyear SEC $1.7B');
eq(Real.get(waste,'C4'),200,'Hypothetical 1000/5 depreciation old life');
eq(Real.get(waste,'C5'),100,'Hypothetical 1000/10 depreciation new life');
eq(Real.get(waste,'C6'),100,'Hypothetical pretax uplift, not SEC fact');
assert.throws(()=>Real.set(waste,'B3','=100'),/read-only/);n++;
eq(SEC.cases.waste.figures.cumulativePretaxMisstatement,1700,'registry case consistent');
for(const key of ['worldcom','xerox','waste'])ok(SEC.linkOK(SEC.cases[key].citation),'new case SEC official link');

const w=Coach.simulate({kind:'worldcom',amount:500,life:5});
eq(w.pretaxOverstatement,500,'capitalization of expense creates $500 pretax profit illusion');
eq(w.laterAnnualDepreciation,100,'straight line depreciation $500/5');
eq(w.immediateCashDifference,0,'accounting classification does not generate new immediate cash');
const x=Coach.simulate({kind:'xerox',amount:100});
eq(x.pretaxOverstatement,100,'premature revenue records hypothetical $100 pretax uplift');
eq(x.immediateCashDifference,0,'premature recognition not cash received');
const z=Coach.simulate({kind:'waste',amount:1000,life:5});
eq(z.annualDepreciationOriginal,200,'old life 5 years');
eq(z.annualDepreciationExtended,100,'new life 10 years');
eq(z.illustrativePretaxProfitIncrease,100,'effect on pretax profit');
const r=Coach.simulate({kind:'sunbeam',amount:20});
eq(r.reserveLiabilityChange,-20,'reserve release liability down');
eq(r.immediateCashDifference,0,'reserve release no cash');
const d=Coach.simulate({kind:'dell',amount:76});
eq(d.otherOperatingIncome,24,'Dell dependence is hypothetical $100 model only');
assert.throws(()=>Coach.simulate({kind:'worldcom',amount:-1}),/must be/);n++;
assert.throws(()=>Coach.simulate({kind:'waste',amount:100,life:0}),/must be|Unknown/);n++;
ok(Coach.simulatorHTML('zh').includes('非真实历史金额'),'simulator disclaimer in Chinese');
ok(!Coach.renderSimResult(w).includes('<script>'),'simulation renders safe text');
console.log(n+' Flo guided learning, SEC cases, account-simulation tests passed');
