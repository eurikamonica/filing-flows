const assert = require('node:assert/strict');
const A = require('../web/appearance.js');
assert.deepEqual(A.sanitize(null), A.defaults);
assert.equal(A.sanitize({skin:'<script>',color:'bad',grain:99,power:-2}).skin,'original');
assert.equal(A.sanitize({grain:99,power:-2}).grain,30);
assert.equal(A.sanitize({grain:99,power:-2}).power,0);
const p={...A.defaults,season:'auto',holiday:'auto'};
assert.equal(A.calendar(p,new Date(2026,11,25)).holiday,'christmas');
assert.equal(A.calendar(p,new Date(2026,10,26)).holiday,'thanks');
assert.equal(A.calendar(p,new Date(2026,10,19)).holiday,'none');
assert.equal(A.calendar(p,new Date(2026,1,17)).holiday,'lunar');
assert.equal(A.calendar(p,new Date(2026,6,4)).season,'summer');
assert.equal(A.calendar({...p,hemisphere:'south'},new Date(2026,6,4)).season,'winter');
const now=Date.parse('2026-10-25T12:00:00Z');
assert.equal(A.weeklyState({start:'2026-10-16',c:[100,110]},now).mood,'happy');
assert.equal(A.weeklyState({start:'2026-10-16',c:[100,90]},now).mood,'worried');
assert.equal(A.weeklyState({start:'2026-10-16',c:[100,100]},now).mood,'idle');
assert.equal(A.weeklyState({start:'2026-10-01',c:[100,110]},now).mood,'idle');
assert.equal(A.weeklyState({start:'2026-10-30',c:[100,110]},now).mood,'idle');
assert.equal(A.weeklyState({start:'2026-10-16',c:[null,110]},now).mood,'idle');
assert.equal(A.sectorSkin('financials'),'finance');
assert.equal(A.sectorSkin('consumer-staples'),'consumer');
assert.equal(A.sectorSkin('health-care'),'health');
assert.equal(A.sectorSkin('information-technology'),'tech');
console.log('Appearance: defaults, validation, calendar, sectors, freshness and weekly-return tests passed.');
